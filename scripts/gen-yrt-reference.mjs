// =============================================================================
// gen-yrt-reference.mjs — build a human-readable YRT reference from the JSON.
//
// The Iron Ledger repo's extensions/yrt/{foes,moves,assets,oracles} JSON is the
// single source of truth for the YRT game content. This generator renders it
// into Markdown reference pages under extensions/yrt/reference/, so the wiki /
// worldbuilding garden (and anyone browsing the repo) has an always-in-sync,
// readable view without a second hand-maintained copy that can drift.
//
// Output (committed, generator-owned; regenerate — never hand-edit):
//   extensions/yrt/reference/bestiary.md   — the 24 foes
//   extensions/yrt/reference/moves.md      — YRT moves
//   extensions/yrt/reference/assets.md     — assets + rarities
//   extensions/yrt/reference/oracles.md    — oracle tables
//
// Deterministic output (no timestamps) so regeneration is a no-op in git.
//
//   node scripts/gen-yrt-reference.mjs         # write the reference
//   node scripts/gen-yrt-reference.mjs --check # fail if stale (CI)
// =============================================================================

import { readFile, writeFile, readdir, mkdir } from 'fs/promises';
import { existsSync } from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const YRT = path.join(ROOT, 'extensions/yrt');
const OUT = path.join(YRT, 'reference');
const check = process.argv.includes('--check');

const readJson = async (p) => JSON.parse(await readFile(p, 'utf8'));

// App-internal DSL links ([label](move:…)/(oracle:…)/(resource:…)/(roll:…)) have
// no meaning outside the app — render them as their plain label. Real http(s)
// links are kept.
const stripDsl = (s = '') => s.replace(/\[([^\]]+)\]\((?!https?:)[^)]*\)/g, '$1');
const clean = (s = '') =>
  stripDsl(String(s))
    .replace(/[ \t]+\n/g, '\n')
    .trim();

// Oracle values are usually strings, but some tables (e.g. Touched: class) carry
// a structured object per row — render those readably.
const renderVal = (v) => {
  if (typeof v === 'string') return clean(v);
  if (v && typeof v === 'object') {
    if (v.className)
      return `**${v.className}**${v.description ? ` — ${clean(v.description)}` : ''}`;
    if (v.prefix != null || v.suffix != null) return clean(`${v.prefix ?? ''}${v.suffix ?? ''}`);
    if (v.value != null) return clean(String(v.value));
    return clean(JSON.stringify(v));
  }
  return clean(String(v));
};
const RANK = { 1: 'Troublesome', 2: 'Dangerous', 3: 'Formidable', 4: 'Extreme', 5: 'Epic' };

const HEADER = (title) =>
  [
    `<!-- GENERATED by scripts/gen-yrt-reference.mjs — do not edit by hand.`,
    `     Source of truth: extensions/yrt/. Run \`npm run gen:yrt-ref\`. -->`,
    ``,
    `# ${title}`,
    ``,
  ].join('\n');

const bullets = (arr) => (arr || []).map((x) => `- ${clean(x)}`).join('\n');

// ── Bestiary ────────────────────────────────────────────────────────────────
function renderBestiary(foes) {
  const out = [HEADER('YRT Bestiary')];
  foes.forEach((f, i) => {
    const yrt = f.extras?.yrt ?? {};
    const nature =
      (f.natureNote ?? yrt.natureNote)
        ? `${f.nature} (${f.natureNote ?? yrt.natureNote})`
        : f.nature;
    const s = [`## ${i + 1}. ${f.name}`, ''];
    if (f.images?.[0]) {
      s.push(`![${clean(yrt.caption ?? f.name)}](../foes/images/${f.images[0]})`);
      if (yrt.caption) s.push('', `*${clean(yrt.caption)}*`);
      s.push('');
    }
    if (yrt.rework) s.push(`*Reworked from: ${clean(yrt.rework)}*`, '');
    s.push(`**Rank:** ${f.rank} — ${RANK[f.rank]} · **Nature:** ${nature}`, '');
    if (f.features?.length) s.push('**Features:**', bullets(f.features), '');
    if (f.drives?.length) s.push('**Drives:**', bullets(f.drives), '');
    if (f.tactics?.length) s.push('**Tactics:**', bullets(f.tactics), '');
    if (yrt.escalates)
      s.push('> **Escalating Harm** (YRT): harm rises on each miss, capped by rank.', '');
    if (yrt.escalatesDefense)
      s.push('> **Escalating Defense** (YRT): a mana shield erodes on each miss.', '');
    if (f.description) s.push(clean(f.description), '');
    out.push(s.join('\n'));
  });
  return out.join('\n') + '\n';
}

// ── Moves ─────────────────────────────────────────────────────────────────────
function renderMoves(moves) {
  const out = [HEADER('YRT Moves')];
  for (const m of moves) {
    const s = [`## ${m.name}`, ''];
    if (m.triggerShort) s.push(`*${clean(m.triggerShort)}*`, '');
    if (m.trigger) s.push(clean(m.trigger), '');
    if (m.strong) s.push(`**Strong Hit:** ${clean(m.strong)}`, '');
    if (m.weak) s.push(`**Weak Hit:** ${clean(m.weak)}`, '');
    if (m.miss) s.push(`**Miss:** ${clean(m.miss)}`, '');
    out.push(s.join('\n'));
  }
  return out.join('\n') + '\n';
}

// ── Assets + Rarities ─────────────────────────────────────────────────────────
function renderAssets(assets, rarities) {
  const out = [HEADER('YRT Assets')];
  for (const a of assets) {
    const s = [`## ${a.name}`, `*${a.category}*`, ''];
    if (a.summary) s.push(clean(a.summary), '');
    if (a.preamble) s.push(clean(a.preamble), '');
    (a.abilities || []).forEach((ab) => {
      if (ab?.text) s.push(`- ${ab.enabled ? '**◉**' : '◯'} ${clean(ab.text)}`);
    });
    if (a.abilities?.length) s.push('');
    if (a.postamble) s.push(clean(a.postamble), '');
    out.push(s.join('\n'));
  }
  if (rarities?.length) {
    out.push('## Rarities\n');
    for (const r of rarities) {
      out.push(
        `### ${r.name}\n\n*Rarity · pairs with \`${r.assetId}\` · XP ${r.xpCost}*\n\n${clean(r.description)}\n`,
      );
    }
  }
  return out.join('\n') + '\n';
}

// ── Oracles ───────────────────────────────────────────────────────────────────
function renderOracles(oracles) {
  const out = [HEADER('YRT Oracles')];
  // Stable order by title.
  for (const o of oracles.sort((a, b) => (a.title || '').localeCompare(b.title || ''))) {
    const s = [`## ${o.title}`, ''];
    if (o.description) s.push(clean(o.description), '');
    if (o.tableType === 'columnSelect' && o.columns?.length) {
      const cols = o.columns;
      s.push(`| ${cols.map((c) => c.label).join(' | ')} | Result |`);
      s.push(`| ${cols.map(() => '---').join(' | ')} | --- |`);
      for (const row of o.data)
        s.push(`| ${cols.map((c) => row[c.key] ?? '').join(' | ')} | ${clean(row.value)} |`);
    } else if (Array.isArray(o.data)) {
      s.push('| d100 | Result |', '| --- | --- |');
      let lo = 1;
      for (const row of o.data) {
        const hi = row.topRange;
        s.push(`| ${lo === hi ? lo : `${lo}–${hi}`} | ${renderVal(row.value)} |`);
        lo = hi + 1;
      }
    }
    s.push('');
    if (o.postamble) s.push(clean(o.postamble), '');
    out.push(s.join('\n'));
  }
  return out.join('\n') + '\n';
}

// ── main ──────────────────────────────────────────────────────────────────────
const foes = (await readJson(path.join(YRT, 'foes/foes.json'))).foes;
const moves = (await readJson(path.join(YRT, 'moves/moves.json'))).moves;
const assetsFile = await readJson(path.join(YRT, 'assets/assets.json'));
const oracleFiles = (await readdir(path.join(YRT, 'oracles'))).filter((f) => f.endsWith('.json'));
const oracles = await Promise.all(oracleFiles.map((f) => readJson(path.join(YRT, 'oracles', f))));

const files = {
  'bestiary.md': renderBestiary(foes),
  'moves.md': renderMoves(moves),
  'assets.md': renderAssets(assetsFile.assets, assetsFile.rarities),
  'oracles.md': renderOracles(oracles),
};

if (check) {
  const stale = [];
  for (const [name, body] of Object.entries(files)) {
    const p = path.join(OUT, name);
    const cur = existsSync(p) ? await readFile(p, 'utf8') : null;
    if (cur !== body) stale.push(`extensions/yrt/reference/${name}`);
  }
  if (stale.length) {
    console.error(
      `✗ YRT reference is stale:\n  - ${stale.join('\n  - ')}\n  Run \`npm run gen:yrt-ref\` and commit.`,
    );
    process.exit(1);
  }
  console.log('✓ YRT reference up to date');
} else {
  if (!existsSync(OUT)) await mkdir(OUT, { recursive: true });
  await Promise.all(Object.entries(files).map(([n, b]) => writeFile(path.join(OUT, n), b)));
  console.log(
    `✓ wrote YRT reference (${foes.length} foes, ${moves.length} moves, ` +
      `${assetsFile.assets.length} assets + ${assetsFile.rarities?.length ?? 0} rarities, ${oracles.length} oracles)`,
  );
}
